def t(key: str, lang: str = "en") -> str:
    return MESSAGES.get(lang, MESSAGES["en"]).get(
        key,
        MESSAGES["en"].get(key, key),
    )


def format_warning(warning: str, lang: str = "en") -> str:
    key = f"warn_{warning}"
    translated = t(key, lang)
    if translated != key:
        return translated
    return str(warning)